#!/usr/bin/env python3
"""Verify this repo's delegated-agent security boundary.

The boundary is `.claude/agent-policy.json`, interpreted by the shared harness at
~/.claude/bin/delegate.py. That script is machine-wide and serves several repos, so
nothing in this repo pins its behaviour -- an upstream edit, or a reinstall from an
older copy, could widen or replace this repo's boundary without a file here
changing. This test is the pin.

Generated by init-agent-harness.py. Extend ALLOWED and REFUSED as the policy grows:
a rule nobody asserted is a rule nobody will notice losing.

    python tools/agent-harness/selftest_policy.py
"""
import importlib.util
import json
import os
import pathlib
import sys
import tempfile

REPO = pathlib.Path(__file__).resolve().parents[2]
HARNESS = pathlib.Path.home() / ".claude" / "bin" / "delegate.py"
MIN_HARNESS_VERSION = 2      # 2 introduced per-repo policy loading

if not HARNESS.exists():
    sys.exit(f"error: harness not installed at {HARNESS}")

spec = importlib.util.spec_from_file_location("delegate_under_test", HARNESS)
delegate = importlib.util.module_from_spec(spec)
spec.loader.exec_module(delegate)

installed = getattr(delegate, "HARNESS_VERSION", 0)
if installed < MIN_HARNESS_VERSION:
    sys.exit(f"error: {HARNESS} is harness version {installed or 'pre-2'}, need "
             f">= {MIN_HARNESS_VERSION}. Below that, .claude/agent-policy.json is "
             "IGNORED and agents run under the harness built-in allowlist instead "
             "of this repo's. Reinstall the current harness; do not restore it by "
             "copying an older copy out of another repo.")

failures = []


def check(label, condition):
    if not condition:
        failures.append(label)


note = delegate.load_policy(str(REPO))
check("policy file not found; the run would fall back to the built-ins",
      ".claude" in note and "built-in" not in note)

policy = json.loads((REPO / ".claude" / "agent-policy.json").read_text(encoding="utf-8"))
check("ALLOWED_CMDS does not match the policy file",
      delegate.ALLOWED_CMDS == [list(r) for r in policy["allowed_cmds"]])
check("SKIP_DIRS does not match the policy file",
      delegate.SKIP_DIRS == set(policy["skip_dirs"]))

# The model must be told the ACTIVE allowlist, not the built-in one.
docs = {name: desc for name, _a, desc in delegate.tool_docs()}
check("run_command's description does not advertise this repo's allowlist",
      " ".join(policy["allowed_cmds"][0]) in docs["run_command"])
check("the read limit stated to the model is not the one enforced",
      f"{delegate.MAX_READ_CHARS:,}" in docs["read_file"])


class FakeCompleted:
    returncode, stdout, stderr = 0, "", ""


executed = []
real_run = delegate.subprocess.run
delegate.subprocess.run = lambda argv, **kw: (executed.append(argv), FakeCompleted())[1]
runner = delegate.Runner(str(REPO), write_mode="stage")

# Nothing is executed: allowed commands may have real side effects, so proving
# they are PERMITTED must not run them.
ALLOWED = [list(r) for r in policy["allowed_cmds"]]

REFUSED = [
    ["npm", "test"] if ["npm", "test"] not in ALLOWED else ["npm", "publish"],
    ["python", "-c", "import shutil"],
    ["bash", "-c", "ls"],
    ["powershell", "-Command", "ls"],
    ["rm", "-rf", "src"],
    ["git", "push"],
    ["git", "commit", "-m", "x"],
    ["python", "scripts/../../evil.py"],
    ["python", "/tmp/evil.py"],
    # Narrowed 2026-09-24: no agent may reach the operator-gated scripts. The first
    # replaces the SHARED engine at ~/.claude/bin/delegate.py for every repo; the
    # second can apply live migration. Assert both spellings, since rules match
    # argv positionally and a '-u' rule would be a second doorway.
    ["python", "scripts/deploy_engine.py", "--apply"],
    ["python", "-u", "scripts/deploy_engine.py", "--apply"],
    ["python", "scripts/migrate_existing.py", "--apply"],
    ["python", "scripts/verify_reconciliation.py"],
    ["python", "-u", "-c", "import shutil"],
    # The node rule is pinned to tests/js/ in slot 3; '-e' and other targets stay out.
    ["node", "-e", "require('fs')"],
    ["node", "--test", "scripts/evil.mjs"],
    ["node", "--test", "tests/js/../../evil.mjs"],
    ["node", "scripts/x.mjs"],
    # pytest collects AND RUNS whatever file it is handed, so the path guard must
    # hold for the trailing argument in both slash directions.
    ["python", "-m", "pytest", "/tmp/evil_test.py"],
    ["python", "-m", "pytest", "\\\\server\\share\\evil_test.py"],
    ["python", "-m", "py_compile", "/tmp/evil.py"],
]

for argv in ALLOWED:
    concrete = [a.replace("*", "x") for a in argv]
    executed.clear()
    out = runner.run_command(concrete)
    check(f"should be ALLOWED but was not run: {' '.join(concrete)} -> {out[:80]}",
          not out.startswith("refused:") and len(executed) == 1)

for argv in REFUSED:
    executed.clear()
    out = runner.run_command(argv)
    check(f"should be REFUSED but was permitted: {' '.join(argv)}",
          out.startswith("refused:"))
    check(f"REFUSED command still reached the shell: {' '.join(argv)}", not executed)

delegate.subprocess.run = real_run
if hasattr(runner, "close"):
    runner.close()


def policy_exits(text, label):
    """A policy the loader cannot trust must exit, never fall back silently."""
    with tempfile.TemporaryDirectory() as d:
        os.makedirs(os.path.join(d, ".claude"))
        with open(os.path.join(d, ".claude", "agent-policy.json"), "w",
                  encoding="utf-8") as fh:
            fh.write(text)
        try:
            delegate.load_policy(d)
        except SystemExit:
            return
        failures.append(f"a {label} policy did not fail closed")


policy_exits("{ not json", "malformed")
policy_exits('{"allowed_cmd": [["git","status"]]}', "misspelled-key")
policy_exits('{"allowed_cmds": "git status"}', "wrong-type")
policy_exits('{"allowed_cmds": []}', "empty")

# Capability support is pinned by feature presence, not a new version number.
mcp_checked = False
if "mcp" not in getattr(delegate, "POLICY_KEYS", ()):
    failures.append("installed harness lacks MCP policy support")
else:
    policy_exits('{"mcp": {"unexpected": 1}}', "unknown MCP key")
    policy_exits('{"mcp": {"servers": []}}', "wrong-type MCP servers")
    command = ["selftest-mcp-server", "--stdio"]
    policy_exits(json.dumps({"mcp": {"allowed_commands": [], "servers": {
        "test": {"command": command, "enabled": True}}}}),
        "MCP command outside exact launch authorizations")
    try:
        hm = delegate.capability_module("harness_mcp")
        pol = hm.validate_mcp_policy({"allowed_commands": [command], "servers": {
            "test": {"command": command, "allowed_tools": ["read_*", "write_*"],
                     "mutating_tools": ["write_*"], "enabled": True}}})
        launched = []
        real_popen = hm.subprocess.Popen
        def no_launch(*args, **kwargs):
            launched.append(args)
            raise AssertionError("a refusal attempted to launch an MCP server")
        hm.subprocess.Popen = no_launch
        try:
            with tempfile.TemporaryDirectory() as root:
                manager = hm.MCPManager(pol, root, allow_mutation=False)
                try:
                    for tool in ("other_tool", "write_file"):
                        manager._tools[f"mcp__test__{tool}"] = {
                            "server": "test", "tool": tool, "description": "",
                            "schema": {"type": "object"}, "mutating": False}
                    for name in ("mcp__absent__read_x", "mcp__test__other_tool",
                                 "mcp__test__write_file"):
                        try:
                            manager.call(name, {})
                        except ValueError as exc:
                            check(f"MCP refusal not explicit: {name}",
                                  str(exc).startswith("refused:"))
                        else:
                            failures.append(f"MCP tool should be refused: {name}")
                    check("MCP refusals launched a server", not launched)
                finally:
                    manager.close()
        finally:
            hm.subprocess.Popen = real_popen
        mcp_checked = True
    except Exception as exc:
        failures.append(f"MCP boundary selftest failed: {type(exc).__name__}")

delegate.load_policy(str(REPO))

if failures:
    print(f"selftest_policy: FAIL ({len(failures)})", file=sys.stderr)
    for f in failures:
        print(f"  - {f}", file=sys.stderr)
    sys.exit(1)
print(f"selftest_policy: PASS ({len(ALLOWED)} allowed, {len(REFUSED)} refused, "
      f"mcp={'checked' if mcp_checked else 'missing'})")
